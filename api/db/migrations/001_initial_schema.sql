-- 001 Initial schema (Kestrel Digital, Feb 2026)

CREATE TABLE Organisations (
    Id      INT IDENTITY(1,1) PRIMARY KEY,
    Name    NVARCHAR(200) NOT NULL,
    Type    NVARCHAR(20)  NOT NULL   -- Internal | Client
);
GO

CREATE TABLE Users (
    Id              INT IDENTITY(1,1) PRIMARY KEY,
    Email           NVARCHAR(256) NOT NULL,
    PasswordHash    NVARCHAR(400) NOT NULL,
    Role            NVARCHAR(30)  NOT NULL,   -- PlatformAdmin | ClientAdmin | ClientViewer
    OrganisationId  INT NOT NULL REFERENCES Organisations(Id),
    CONSTRAINT UQ_Users_Email UNIQUE (Email)
);
GO

CREATE TABLE Outlets (
    Id          INT IDENTITY(1,1) PRIMARY KEY,
    StpNumber   CHAR(6)        NOT NULL,      -- 6-digit store identifier, leading zeros are significant
    Name        NVARCHAR(200)  NOT NULL,
    Province    NVARCHAR(50)   NOT NULL,
    Latitude    DECIMAL(9,6)   NULL,
    Longitude   DECIMAL(9,6)   NULL,
    OwnerName   NVARCHAR(200)  NULL,
    ApStatus    NVARCHAR(20)   NOT NULL,      -- Online | Offline | NotInstalled
    IsActive    BIT            NOT NULL DEFAULT 1,
    CreatedAt   DATETIMEOFFSET NOT NULL,
    UpdatedAt   DATETIMEOFFSET NOT NULL,
    CONSTRAINT UQ_Outlets_Stp UNIQUE (StpNumber)
);
GO

CREATE TABLE Campaigns (
    Id              INT IDENTITY(1,1) PRIMARY KEY,
    OrganisationId  INT NOT NULL REFERENCES Organisations(Id),
    Name            NVARCHAR(200)  NOT NULL,
    Status          NVARCHAR(20)   NOT NULL,  -- Draft | Scheduled | Live | Ended
    StartsAt        DATETIMEOFFSET NOT NULL,  -- inclusive
    EndsAt          DATETIMEOFFSET NOT NULL,  -- exclusive
    BudgetZar       DECIMAL(12,2)  NOT NULL,
    CreatedAt       DATETIMEOFFSET NOT NULL,
    UpdatedAt       DATETIMEOFFSET NOT NULL
);
GO

CREATE TABLE CampaignOutlets (
    CampaignId  INT NOT NULL REFERENCES Campaigns(Id),
    OutletId    INT NOT NULL REFERENCES Outlets(Id),
    CONSTRAINT PK_CampaignOutlets PRIMARY KEY (CampaignId, OutletId)
);
GO

CREATE TABLE ConnectionEvents (
    Id          BIGINT IDENTITY(1,1) PRIMARY KEY,
    EventId     UNIQUEIDENTIFIER NOT NULL,    -- generated by the portal
    OutletId    INT NOT NULL REFERENCES Outlets(Id),
    CampaignId  INT NULL REFERENCES Campaigns(Id),
    DeviceHash  NVARCHAR(64)   NOT NULL,
    EventType   NVARCHAR(30)   NOT NULL,      -- connect | portal_view | ad_complete | survey_complete
    OccurredAt  DATETIMEOFFSET NOT NULL,
    Msisdn      NVARCHAR(20)   NULL,          -- captured at sign-in when the user opts in
    ReceivedAt  DATETIMEOFFSET NOT NULL DEFAULT SYSDATETIMEOFFSET()
);
GO
